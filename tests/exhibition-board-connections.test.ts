const id = () => crypto.randomUUID();
const board = (x: number): BoardGroup => ({ id: id(), name: '展示ボード', x, y: 1000, rotation: 0, panels: [{ id: id(), name: 'パネル', width: 900, height: 1800, thickness: 30, hingeAngle: 0 }] });
const room = (): RoomLayout => ({ id: id(), name: '会場', vertices: [{ x: 0, y: 0 }, { x: 6000, y: 0 }, { x: 6000, y: 4000 }, { x: 0, y: 4000 }], wallHeights: [3000,3000,3000,3000], openings: [], placements: [], tables: [], books: [], boardGroups: [board(1000),board(1900),board(2800)] });
test('legacy adjacent groups become one chain with every panel, preserving geometry and A/B content', () => {
  const r = room(), groups = r.boardGroups!, first = groups[0], last = groups[2];
  r.boardPlacements = [{ workId: id(), groupId: first.id, face: 'B', x: 100, bottom: 800, rotation: 0 }, { workId: id(), groupId: last.id, face: 'A', x: 200, bottom: 900, rotation: 0 }];
  r.annotations = [{ id: id(), kind: 'text', x: 120, y: 100, width: 300, height: 100, rotation: 0, text: 'B面', fontSize: 80, surface: `board:${first.id}:B` }];
  r.titleBoards = [{ id: id(), workId: r.boardPlacements[1].workId, surface: `board:${last.id}:A`, x: 200, bottom: 700, rotation: 0 }];
  const before = structuredClone(r), physical = groups.flatMap(boardChain), next = connectTouchingBoards(r);
  assert.deepEqual(r, before);
  assert.equal(next.boardGroups!.length, 1);
  assert.deepEqual(boardChain(next.boardGroups![0]), physical);
  assert.equal(boardSurface(next.boardGroups![0],'A').width,2700);
  assert.equal(boardSurface(next.boardGroups![0],'B').panels[0].panel.id,last.panels[0].id);
  assert.deepEqual(next.boardPlacements!.map(p=>p.x),[1900,2000]);
  assert.equal(next.annotations![0].x,1920);
  assert.equal(next.titleBoards![0].x,2000);
  assert.equal(roomSurfaces(next).filter(s=>s.face).length,2);
  assert.ok(roomSurfaces(next).filter(s=>s.face).every(s=>s.panels!.length===3));
  assert.equal(connectTouchingBoards(next),next);
});
