test('moving a bridge connects both sides and disconnected or ambiguous chains remain separate', () => {
  const r=room();
  assert.equal(snapBoardConnection(r,r.boardGroups![1].id,1).boardGroups!.length,1);
  const duplicate=board(1900);
  assert.equal(touchingBoardRuns([...r.boardGroups!,duplicate]).filter(run=>run.length>1).length,0);
  r.boardGroups![1].x+=10;
  assert.equal(touchingBoardRuns(r.boardGroups!).length,3);
});
