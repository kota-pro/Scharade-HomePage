test("exhibition Gallery resolves only submitted assets, identifies the submitter and enforces every audience", async () => {
  const exhibitionId = crypto.randomUUID(), submissionId = crypto.randomUUID(), assetId = crypto.randomUUID(), sectionId = crypto.randomUUID();
  const photo = { assetId, x: 0, y: 0, width: 300, height: 200, rotation: 0, metadata: { camera: "", iso: "" } };
  const work = { id: crypto.randomUUID(), sectionId, kind: "single", title: "", caption: "", location: "", equipment: "", settings: "", fields: {}, photos: [photo] };
  const schema = { version: 1, captionLabel: "説明", fields: [], sections: [{ id: sectionId, title: "展示", description: "" }] };
  const content = { name: "作者", authorName: "作者", grade: "1st Grade", fields: {}, sections: [{ sectionId, singles: 1, series: 0, books: 0, seriesPhotoCounts: [], fields: {} }], works: [work] };
  assert.equal(parseContent(content, schema, [{ id: assetId }] as any).works[0].title, "");
  const bytes = await sharp({ create: { width: 40, height: 30, channels: 3, background: "#ccc" } }).jpeg().toBuffer();
  const data = { version: 1, exhibitions: [{ id: exhibitionId, title: "写真展", albumId: "exhibition-album", status: "closed", gallery: "public", createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() }], submissions: [{ id: submissionId, exhibitionId, userId: owner.id, draft: { ...content, works: [] }, versions: [{ content }] }], assets: [{ id: assetId, exhibitionId, submissionId, lightroomId: "exhibition-asset", name: "写真.jpg", width: 40, height: 30, photoMetadata: { camera: "Nikon Z5", iso: "400" }, sha256: crypto.createHash("sha256").update(bytes).digest("hex") }, { id: "draft-only", exhibitionId, submissionId, lightroomId: "draft-photo", name: "下書き.jpg" }] };
  writeData("exhibitions.json", data); fs.writeFileSync(dataPath(`exhibition-${assetId}.bin`), bytes);
  const page = await getGalleryPhotosPage("exhibition-album", { limit: 100 }); assert.deepEqual(page.photos.map(photo => photo.id), ["exhibition-asset"]);
  const ref = { source: "gallery", containerId: "exhibition-album", imageId: "exhibition-asset" }, resolved = await resolvePhoto(ref);
  assert.equal(resolved.ownerId, owner.id); assert.equal(resolved.notifyOwnerId, owner.id); assert.equal(resolved.camera, ""); assert.equal(resolved.title, "");
  Object.assign(work, { title: "朝霧の湖", caption: "朝の静けさを写した作品です。", details: { film: "Kodak Portra 400" } });
  Object.assign(photo.metadata, { camera: "SONY α7 IV", lens: "FE 24-70mm F2.8 GM II", fNumber: "8", shutterSpeed: "1/125", iso: "200" });
  writeData("exhibitions.json", data);
  const titled = await resolvePhoto(ref);
  assert.equal(titled.film, "Kodak Portra 400");
  Object.assign(photo.metadata, { film: "Ilford HP5 Plus" });
  writeData("exhibitions.json", data);
  assert.equal((await resolvePhoto(ref)).film, "Ilford HP5 Plus");
  assert.deepEqual(Object.fromEntries(["title", "caption", "camera", "lens", "fNumber", "shutterSpeed", "iso"].map(key => [key, titled[key as keyof typeof titled]])), {
    title: work.title, caption: work.caption, camera: "SONY α7 IV", lens: "FE 24-70mm F2.8 GM II", fNumber: "8", shutterSpeed: "1/125", iso: "200",
  });
  await setPhotoLike(resolved, "guest", true); assert.equal(unreadPhotoGroups(owner.id)[0].count, 1);
  const full = photoLinks("exhibition-album", { id: "exhibition-asset", name: "写真" }).full;
  const context = (user: User | null) => ({ url: new URL(full, "https://scharade.jp"), locals: { user }, params: { id: "exhibition-asset" } }) as any;
  assert.equal((await galleryImage(context(null), 2048)).status, 200);
  data.exhibitions[0].gallery = "staff"; writeData("exhibitions.json", data);
  assert.equal(await accessibleAlbum("exhibition-album", owner), null); assert.equal((await galleryImage(context(null), 2048)).status, 404);
  const executive = { id: "executive", approved: true, role: "executive" } as User;
  assert.ok(await accessibleAlbum("exhibition-album", executive)); assert.equal((await galleryImage(context(executive), 2048)).status, 200);
  data.exhibitions[0].gallery = "members"; writeData("exhibitions.json", data); assert.ok(await accessibleAlbum("exhibition-album", owner)); assert.equal(await accessibleAlbum("exhibition-album", null), null);
  await assert.rejects(resolvePhoto({ ...ref, imageId: "draft-photo" }, executive));
  const secondId = crypto.randomUUID();
  work.kind = "series";
  work.photos.push({ ...photo, assetId: secondId, x: 570, y: 10, width: 200, height: 250, rotation: 90 });
  data.assets.push({ ...data.assets[0], id: secondId, lightroomId: "series-photo" });
  writeData("exhibitions.json", data);
  const gallery = await getGalleryPhotosPage("exhibition-album");
  assert.deepEqual(gallery.photos.map(p => p.opensSeries), [true, true]);
  assert.equal((await resolvePhoto(ref, owner)).series, undefined);
  const series = (await resolvePhoto(ref, owner, true)).series!;
  assert.deepEqual(series.metadata, { caption: work.caption, film: "Kodak Portra 400" });
  assert.deepEqual(series.photos.map(p => [p.id, p.x, p.y, p.rotation]), [["exhibition-asset", 0, 0, 0], ["series-photo", 570, 10, 90]]);
  assert.equal(series.width, 570);
  assert.ok(Math.abs(series.height - 210) < .001);
  assert.match(series.photos[1].full, /^\/api\/images\/full\/series-photo\?proof=/);
  const singleId = crypto.randomUUID();
  content.works.push({ ...work, kind: "single", id: crypto.randomUUID(), photos: [{ ...photo, assetId: singleId }] });
  data.assets.push({ ...data.assets[0], id: singleId, lightroomId: "next-work" });
  writeData("exhibitions.json", data);
  const firstWork = await getGalleryPhotosPage("exhibition-album", { groupSeries: true, limit: 1 });
  assert.equal(firstWork.photos.length, 1);
  assert.deepEqual(firstWork.photos[0].series?.shooting, { film: "Kodak Portra 400" });
  assert.deepEqual(firstWork.photos[0].series?.photos.map(p => [p.id, p.x, p.y, p.rotation]), series.photos.map(p => [p.id, p.x, p.y, p.rotation]));
  assert.ok(firstWork.nextCursor);
  const secondWork = await getGalleryPhotosPage("exhibition-album", { groupSeries: true, cursor: firstWork.nextCursor, limit: 1 });
  assert.deepEqual(secondWork.photos.map(p => p.id), ["next-work"]);
  assert.equal(secondWork.nextCursor, null);
  await assert.rejects(getGalleryPhotosPage("exhibition-album", { cursor: firstWork.nextCursor }));
  await assert.rejects(resolvePhoto(ref, null, true));
  writeData("exhibitions.json", { ...data, exhibitions: [{ ...data.exhibitions[0], albumExcludedAssetIds: [secondId] }] });
  assert.deepEqual((await resolvePhoto(ref, owner, true)).series?.photos.map(p => p.id), ["exhibition-asset"]);
  const previewAfterExclusion = await getGalleryPhotosPage("exhibition-album", { groupSeries: true });
  assert.deepEqual(previewAfterExclusion.photos[0].series?.photos.map(p => p.id), ["exhibition-asset"]);
});
test("Lightroom XMP camera tags handle rational values without returning location or serial numbers", () => {
  assert.deepEqual(lightroomPhotoMetadata({ xmp: { tiff: { Make: "Nikon", Model: "Z5" }, aux: { Lens: "55mm", SerialNumber: "private" }, exif: { FNumber: [28, 10], ExposureTime: [1, 400], ISOSpeedRatings: [4000], GPSLatitude: "private" } } }), { camera: "Z5", lens: "55mm", fNumber: "2.8", shutterSpeed: "1/400", iso: "4000" });
  assert.deepEqual(lightroomPhotoMetadata({ xmp: { tiff: { Make: "FUJIFILM", Model: "SP-3000" }, exif: { ISOSpeedRatings: 400 } } }), { iso: "400" });
  assert.deepEqual(lightroomPhotoMetadata({ xmp: { tiff: { Model: "Digitizer" }, exif: { FileSource: 2 } } }), {});
  assert.deepEqual(lightroomPhotoMetadata({ xmp: { aux: { Lens: "0.0mmf0.0" }, exif: { ISO: 400 } } }), { iso: "400" });
  assert.deepEqual(lightroomPhotoMetadata({ xmp: { aux: { Lens: "0.0 mm f/0.0" }, exif: { LensModel: "50mm f/0.95" } } }), { lens: "50mm f/0.95" });
});
