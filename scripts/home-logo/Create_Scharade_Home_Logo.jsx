(function () {
    $.evalFile(new File(File($.fileName).parent.fsName + "/Home_Logo_AE.jsxinc"));
    var options = $.global.scharadeLogoBuild;
    var source = options ? new File(options.source) : File.openDialog("Select the prepared logo-data.json");
    if (!source) return;
    var output = options ? new File(options.project) : File.saveDialog("Save Scharade Home Logo (.aep)");
    if (!output) return;

    var comp;
    app.beginUndoGroup("Create Scharade Home Logo");
    try {
        var data = ScharadeLogoAE.read(source);
        // Older ExtendScript installations expose no JSON global. This file is generated by prepare.py.
        var model = typeof JSON === "undefined" ? eval("(" + data + ")") : JSON.parse(data);
        comp = ScharadeLogoAE.create(model);
        app.project.save(output);
        if (options) ScharadeLogoAE.writeSvg(comp, new File(options.svg));
    } finally {
        app.endUndoGroup();
    }
    comp.openInViewer();
}());
